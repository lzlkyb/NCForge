/* global window, document */
import { chromium } from "playwright";
import { writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = [];
page.on("pageerror", error => { errors.push(String(error)); console.log(error.stack); });
page.on("console", msg => { if (msg.type() === "error") console.log(msg.text()); });
try {
  await page.goto(process.env.NCFORGE_COMPLETION_QA_URL ?? "http://localhost:1428/scripts/java-completion-qa/");
  await page.waitForFunction(() => !!window.qa, { timeout: 30000 });
  const reset = async (index, source) => {
    await page.evaluate(({ index, source }) => window.qa.reset(index, source), { index, source });
  };
  await reset(0, "package demo;\npublic class CompletionDemo {\n  void demo() {\n    /*cursor*/ values;\n  }\n}");
  await page.keyboard.type("ArrayL", { delay: 80 });
  await page.locator(".suggest-widget.visible").waitFor();
  await page.locator(".suggest-widget.visible").getByText(/ArrayList/).first().waitFor();
  await page.screenshot({ path: ".cache/java-completion-popup.png" });
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => window.qa.model.getValue().includes("import java.util.ArrayList;"));
  assert.match(await page.evaluate(() => window.qa.model.getValue()), /ArrayList values/);
  await reset(3, "package demo;\npublic class CompletionDemo {\n  void demo() {\n    StringBuilder builder = new StringBuilder();\n    builder./*cursor*/;\n  }\n}");
  await page.keyboard.type("app", { delay: 80 });
  await page.locator(".suggest-widget.visible").waitFor();
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => window.qa.model.getValue().includes("builder.append("));
  await page.locator(".parameter-hints-widget.visible").waitFor();
  await reset(0, "class Demo { String value = \"/*cursor*/\"; }");
  await page.keyboard.type("ArrayL", { delay: 80 });
  await page.waitForTimeout(500);
  assert.equal(await page.locator(".suggest-widget.visible").count(), 0);
  await reset(0, "class Demo {\n // /*cursor*/\n}");
  await page.keyboard.type("ArrayL", { delay: 80 });
  await page.waitForTimeout(500);
  assert.equal(await page.locator(".suggest-widget.visible").count(), 0);
  await reset(0, "class Demo { void demo() { int localVariable = 1; /*cursor*/; } }");
  await page.keyboard.type("localV", { delay: 80 });
  await page.locator(".suggest-widget.visible").waitFor();
  await page.locator(".suggest-widget.visible").getByText("localVariable", { exact: true }).waitFor();
  const classSource = "package demo;\npublic class CompletionDemo {\n  void demo() {\n    /*cursor*/ values;\n  }\n}";
  await reset(0, classSource);
  await page.evaluate(() => { window.qa.state.lazyImports = true; window.qa.state.delay = 400; });
  await page.keyboard.type("ArrayL", { delay: 80 });
  await page.locator(".suggest-widget.visible").waitFor();
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => window.qa.model.getValue().includes("import java.util.ArrayList;"));
  assert.match(await page.evaluate(() => window.qa.model.getValue()), /ArrayList values/);
  await reset(0, classSource);
  await page.evaluate(() => { window.qa.state.lazyImports = true; window.qa.state.delay = 500; });
  await page.keyboard.type("ArrayL", { delay: 80 });
  await page.locator(".suggest-widget.visible").waitFor();
  await page.keyboard.type("ist", { delay: 30 });
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => window.qa.model.getValue().includes("import java.util.ArrayList;"));
  assert.match(await page.evaluate(() => window.qa.model.getValue()), /ArrayList values/);
  const ncIndex = await page.evaluate(() => window.qa.cases.findIndex(c => c.case === "NC 跨模块未导入类"));
  await reset(ncIndex, classSource);
  await page.keyboard.type("BaseD", { delay: 80 });
  await page.locator(".suggest-widget.visible").getByText(/BaseDAO/).first().waitFor();
  await page.waitForFunction(() => !document.querySelector(".suggest-widget.visible").textContent.includes("按需载入"));
  await page.keyboard.press("Enter");
  await page.waitForFunction(() => window.qa.model.getValue().includes("import nc.bs.dao.BaseDAO;"));
  await reset(ncIndex, classSource);
  await page.evaluate(() => { window.qa.state.delay = 500; });
  await page.keyboard.type("BaseD", { delay: 80 });
  await page.locator(".suggest-widget.visible").getByText(/BaseDAO/).first().waitFor();
  await page.keyboard.type("AO", { delay: 30 });
  await page.keyboard.press("Enter");
  await page.waitForTimeout(1200);
  const ncAccepted = await page.evaluate(() => window.qa.model.getValue());
  assert.match(ncAccepted, /BaseDAO values/);
  // Loading suggestions use a qualified name until JDT has computed a safe import.
  assert.ok(ncAccepted.includes("import nc.bs.dao.BaseDAO;") || ncAccepted.includes("nc.bs.dao.BaseDAO values"));
  await reset(0, classSource);
  await page.evaluate(() => { window.qa.state.lazyImports = true; window.qa.state.delay = 500; });
  await page.keyboard.type("ArrayL", { delay: 80 });
  await page.locator(".suggest-widget.visible").waitFor();
  await page.keyboard.press("Enter");
  await page.evaluate(() => {
    const other = window.qa.store.openModel("C:\\ws\\gl\\Other.java", { text: "class Other {}", encoding: "UTF-8", hasBom: false, eol: "LF", lossless: true, size: 0, mtimeMs: 0 });
    window.qa.editor.setModel(other);
  });
  await page.waitForTimeout(1200);
  assert.equal(await page.evaluate(() => window.qa.editor.getModel().getValue()), "class Other {}");
  assert.deepEqual(errors, []);
  await writeFile(".cache/java-completion-browser.json", JSON.stringify({ passed: ["Automatic class-prefix popup", "Accepted type with import", "Method snippet", "Parameter hints", "No popup in string", "No popup in comment", "Document word fallback", "Accept before import resolve", "Keep typing while resolving", "NC type discovery and import", "Safe qualified type during NC dependency load", "No stale import on model switch"], scope: "Real Monaco plus production providers and document sync, replayed live JDT results" }, null, 2));
  console.log("PASS: real Monaco browser acceptance");
} catch (error) {
  await page.screenshot({ path: ".cache/java-completion-failure.png" });
  console.log(await page.evaluate(() => ({ text: window.qa?.model.getValue(), calls: window.qa?.state.calls, html: document.querySelector(".suggest-widget")?.outerHTML })));
  throw error;
} finally { await browser.close(); }
