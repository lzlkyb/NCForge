#!/usr/bin/env node
/**
 * Tauri 命令契约生成 / 校验。
 *
 * WHY：前端 `invoke("...")` 的命令名是普通字符串，后端重命名/删除命令后 tsc
 * 完全看不见；`#[tauri::command]` 定义了却忘记登记到 `generate_handler!` 也
 * 只在运行时才炸。本脚本以 `src-tauri/src/main.rs` 的注册表为唯一真源，生成
 * TS 联合类型，并交叉校验三层：
 *
 *   1. 注册表 ↔ Rust 定义：双向一致（漏登记 / 登记了不存在都算错）。
 *   2. 注册表 ↔ 前端 invoke 字面量：前端只能调用已登记命令。
 *   3. 已登记但前端从不调用：必须显式登记原因，防止真死命令悄悄堆积。
 *
 * 用法：
 *   node scripts/gen-command-contract.mjs          # 重新生成
 *   node scripts/gen-command-contract.mjs --check  # 只校验（pre-push / CI）
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const MAIN_RS = join(ROOT, "src-tauri", "src", "main.rs");
const RUST_DIR = join(ROOT, "src-tauri", "src");
const SRC_DIR = join(ROOT, "src");
const OUT_FILE = join(SRC_DIR, "lib", "commandContract.generated.ts");

/**
 * 已登记、但前端确实不调用的命令。键 = 命令名，值 = 为什么留着。
 * 只允许放「有意保留」的命令；前端漏接不是理由。
 */
const ALLOW_UNUSED = new Map([
  ["reveal_install_dir", "安装目录入口暂未接前端，命令先保留"],
]);

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

function rel(file) {
  return relative(ROOT, file).split(sep).join("/");
}

/** 从 main.rs 的 generate_handler![...] 提取登记表。 */
function registeredCommands() {
  const src = readFileSync(MAIN_RS, "utf8");
  const m = src.match(/generate_handler!\s*\[([\s\S]*?)\]/);
  if (!m) throw new Error("main.rs 里找不到 tauri::generate_handler![...]");
  const names = [...m[1].matchAll(/\bcommands::([a-z0-9_]+)/g)].map((x) => x[1]);
  const dup = names.filter((n, i) => names.indexOf(n) !== i);
  if (dup.length) throw new Error(`generate_handler! 里有重复命令：${[...new Set(dup)].join("、")}`);
  return names;
}

/** 从 Rust 源码提取所有 #[tauri::command] 定义。 */
function definedCommands() {
  const found = new Map();
  for (const file of walk(RUST_DIR)) {
    if (!file.endsWith(".rs")) continue;
    const src = readFileSync(file, "utf8");
    const re = /#\[tauri::command[^\]]*\]\s*(?:pub\s+)?(?:async\s+)?fn\s+([a-z0-9_]+)/g;
    let m;
    while ((m = re.exec(src))) found.set(m[1], rel(file));
  }
  return found;
}

/**
 * 用 TS 编译器 API 找前端 invoke 字面量。
 * 不用正则：注释、模板字符串、测试 mock 都会造成假阳性。
 */
function invokedCommands() {
  const used = new Map();
  const re = /\.(ts|tsx)$/;
  for (const file of walk(SRC_DIR)) {
    if (!re.test(file) || /\.test\.tsx?$/.test(file)) continue;
    const src = readFileSync(file, "utf8");
    const sf = ts.createSourceFile(file, src, ts.ScriptTarget.Latest, true, file.endsWith("x") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
    const visit = (node) => {
      if (ts.isCallExpression(node)) {
        const callee = node.expression;
        const name = ts.isIdentifier(callee)
          ? callee.text
          : ts.isPropertyAccessExpression(callee) && ts.isIdentifier(callee.name)
            ? callee.name.text
            : "";
        if ((name === "invoke" || name === "invokeOrToast" || name === "tauriInvoke") && node.arguments[0] && ts.isStringLiteral(node.arguments[0])) {
          const cmd = node.arguments[0].text;
          if (!used.has(cmd)) used.set(cmd, rel(file));
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(sf);
  }
  return used;
}

function generatedSource(names) {
  const sorted = [...names].sort();
  return [
    "// @generated by scripts/gen-command-contract.mjs — 不要手改。",
    "// 真源：src-tauri/src/main.rs 的 tauri::generate_handler![...]。",
    "// 校验：node scripts/gen-command-contract.mjs --check",
    "",
    "export const TAURI_COMMANDS = [",
    ...sorted.map((n) => `  "${n}",`),
    "] as const;",
    "",
    "export type TauriCommand = (typeof TAURI_COMMANDS)[number];",
    "",
  ].join("\n");
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const registered = registeredCommands();
  const defined = definedCommands();
  const used = invokedCommands();

  const problems = [];
  const regSet = new Set(registered);
  const defSet = new Set(defined.keys());

  for (const n of registered) {
    if (!defSet.has(n)) problems.push(`登记了但源码里没有 #[tauri::command] 定义：${n}`);
  }
  for (const [n, file] of defined) {
    if (!regSet.has(n)) problems.push(`定义了但没登记到 generate_handler!：${n}（${file}）`);
  }
  for (const [n, file] of used) {
    if (!regSet.has(n)) problems.push(`前端调用了未登记的命令：${n}（${file}）`);
  }
  for (const n of registered) {
    if (!used.has(n) && !ALLOW_UNUSED.has(n)) {
      problems.push(`命令已登记但前端从未调用：${n}（确认是死代码就删除；有意保留请登记到 ALLOW_UNUSED）`);
    }
  }

  const out = generatedSource(registered);
  const stale = !existsSyncSafe(OUT_FILE) || readFileSync(OUT_FILE, "utf8") !== out;

  if (problems.length) {
    console.error("❌ 命令契约不一致：");
    for (const p of problems) console.error(`  - ${p}`);
    process.exit(1);
  }

  if (checkOnly) {
    if (stale) {
      console.error("❌ 命令契约文件已过期：src/lib/commandContract.generated.ts");
      console.error("   运行 node scripts/gen-command-contract.mjs 重新生成。");
      process.exit(1);
    }
    console.log(`✅ 命令契约一致（${registered.length} 条命令）`);
    return;
  }

  if (stale) writeFileSync(OUT_FILE, out, "utf8");
  console.log(`✅ 命令契约已生成 / 校验通过（${registered.length} 条命令）`);
}

function existsSyncSafe(p) {
  try {
    statSync(p);
    return true;
  } catch {
    return false;
  }
}

main();
