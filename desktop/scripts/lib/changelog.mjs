const CATEGORIES = { 新增: 'feat', 变更: 'improve', 改进: 'improve', 优化: 'improve', 修复: 'fix', 安全: 'sec' };
const clean = text => text.replace(/\*\*/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/\s+/g, ' ').trim();

function paragraphs(lines) {
 const result = []; let text = '';
 for (const line of lines) {
  if (!line.trim() || /^\s*[-*]\s+/.test(line)) { if (text) result.push(clean(text)); text = line.replace(/^\s*[-*]\s+/, ''); }
  else text += ' ' + line;
 }
 if (text) result.push(clean(text));
 return result.filter(Boolean);
}

/** Public and engineering notes have different audiences; preserve both without flattening code into user bullets. */
export function parseChangelog(markdown) {
 const entries = []; let current = null, section = '', lines = [], fence = null;
 const flush = () => {
  if (!current || !lines.some(line => line.trim())) { lines = []; return; }
  if (section === '更新摘要') current.summary = paragraphs(lines);
  else if (section === '亮点' || section === 'Highlights') current.highlights = paragraphs(lines);
  else if (CATEGORIES[section]) {
   let text = '', inCode = false, code = [];
   const item = () => { if (text.trim()) current.items.push({ category: CATEGORIES[section], text: clean(text) }); text = ''; };
   for (const line of lines) {
    if (/^\s*(```|~~~)/.test(line)) {
     inCode = !inCode; code.push(line);
     if (!inCode) { (current.technical ??= []).push({ heading: section + ' · 示例', text: code.join('\n') }); code = []; }
    } else if (inCode) code.push(line);
    else if (/^[-*]\s+/.test(line)) { item(); text = line.replace(/^[-*]\s+/, ''); }
    else if (text && line.trim()) text += ' ' + line;
   }
   item();
   if (code.length) (current.technical ??= []).push({ heading: section + ' · 示例', text: code.join('\n') });
  } else if (section !== '用户摘要') {
   (current.technical ??= []).push({ heading: section || '技术记录', text: lines.join('\n').trim() });
  }
  lines = [];
 };
 for (const line of markdown.split(/\r?\n/)) {
  const marker = /^\s*(```|~~~)/.exec(line)?.[1];
  if (marker) { fence = fence === marker ? null : fence ?? marker; if (current) lines.push(line); continue; }
  if (fence) { if (current) lines.push(line); continue; }
  if (/^##\s+/.test(line)) {
   flush();
   const match = /^##\s+\[v?(\d+\.\d+\.\d+)\]\s*-\s*(\d{4}-\d{2}-\d{2})\s*$/.exec(line);
   current = match ? { version: match[1], date: match[2], items: [] } : null;
   if (current) entries.push(current);
   section = ''; continue;
  }
  const heading = /^###\s+(.+)$/.exec(line);
  if (heading && current) { flush(); section = heading[1].trim(); continue; }
  if (current) lines.push(line);
 }
 flush();
 return entries.sort((a, b) => {
  const left = a.version.split('.').map(Number), right = b.version.split('.').map(Number);
  return right[0] - left[0] || right[1] - left[1] || right[2] - left[2];
 });
}

export function renderChangelog(entries) {
 return '// AUTO-GENERATED by scripts/gen-changelog.mjs — DO NOT EDIT.\n' +
  '// 数据源：根目录 CHANGELOG.md；保留用户摘要与按需阅读的技术记录。\n' +
  'import type { ChangelogEntry } from "./about";\n\n' +
  `export const CHANGELOG: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};\n`;
}
