"""Vendor OFL fonts locally. Development only: requires fonttools[woff]."""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import json
import re
import urllib.request
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src/assets/fonts"
LICENSES = ROOT / "public/licenses/fonts"
ASSETS.mkdir(parents=True, exist_ok=True)
LICENSES.mkdir(parents=True, exist_ok=True)
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36"


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=45) as response:
        return response.read()


css_url = "https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@100..900&display=swap"
css = fetch(css_url).decode("utf-8")
urls = list(dict.fromkeys(re.findall(r"url\((https:[^)]+)\)", css)))
records = []


def noto_asset(item):
    index, url = item
    data = fetch(url)
    name = "NotoSansSC-Latin.woff2" if index == len(urls) - 1 else f"NotoSansSC-{index:03}.woff2"
    font = TTFont(BytesIO(data))
    assert font["fvar"].axes[0].axisTag == "wght"
    (ASSETS / name).write_bytes(data)
    return {"file": name, "url": url, "bytes": len(data), "sha256": sha256(data).hexdigest()}


with ThreadPoolExecutor(max_workers=6) as executor:
    records.extend(executor.map(noto_asset, enumerate(urls)))
for record in records:
    css = css.replace(record["url"], "./assets/fonts/" + record["file"])

mono_css = []
for italic in (False, True):
    stem = "JetBrainsMono-Italic" if italic else "JetBrainsMono"
    url = f"https://raw.githubusercontent.com/JetBrains/JetBrainsMono/master/fonts/variable/{stem}%5Bwght%5D.ttf"
    source = fetch(url)
    font = TTFont(BytesIO(source))
    assert font["fvar"].axes[0].axisTag == "wght"
    font.flavor = "woff2"
    name = stem + ".woff2"
    path = ASSETS / name
    font.save(path)
    data = path.read_bytes()
    records.append({"file": name, "url": url, "sourceSha256": sha256(source).hexdigest(), "bytes": len(data), "sha256": sha256(data).hexdigest()})
    mono_css.append("\n".join([
        "@font-face {", '  font-family: "JetBrains Mono";',
        f'  font-style: {"italic" if italic else "normal"};',
        "  font-weight: 100 800;", "  font-display: swap;",
        f'  src: url("./assets/fonts/{name}") format("woff2");', "}",
    ]))

css_header = "/* Vendored OFL fonts; generated by scripts/vendor-fonts.py. All URLs are local. */\n"
css_footer = '\n:root {\n  --font-sans: "Noto Sans SC", "Segoe UI", "Microsoft YaHei UI", sans-serif;\n  --font-mono: "JetBrains Mono", "Noto Sans SC", Consolas, monospace;\n}\n'
(ROOT / "src/fonts.css").write_text(css_header + "\n".join(mono_css) + "\n" + css + css_footer, encoding="utf-8", newline="\n")

licenses = {
    "JetBrainsMono-OFL.txt": "https://raw.githubusercontent.com/JetBrains/JetBrainsMono/master/OFL.txt",
    "NotoSansSC-OFL.txt": "https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/OFL.txt",
}
for name, url in licenses.items():
    (LICENSES / name).write_bytes(fetch(url))
manifest = {"cssSource": css_url, "license": "SIL Open Font License 1.1", "assets": records, "totalBytes": sum(r["bytes"] for r in records)}
(LICENSES / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
print(json.dumps({"files": len(records), "totalMB": round(manifest["totalBytes"] / 1024 / 1024, 2)}, ensure_ascii=False))
